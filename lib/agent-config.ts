// The voice agent's configuration as a versioned artefact. Paste it into Vaani, or let Vaani fetch /api/voice/config.
import { appBase } from './env';
import { buildAgentPrompt, OPENING_LINE } from './rules/defaults';
import type { HouseRules } from './types';

export function buildAgentConfig(rules: HouseRules) {
  const prompt = buildAgentPrompt(rules);
  const json = {
    name: 'Aangan Studio phone assistant',
    version: rules.version,
    approved: !!rules.approved_at,
    approved_by: rules.approved_by ?? null,
    approved_at: rules.approved_at ?? null,
    greeting: OPENING_LINE,
    languages: ['en-IN', 'hi-IN', 'mr-IN'],
    language_note: 'English, Hindi, Marathi or Hinglish: mirror the caller. Choose the platform setting that auto-detects or defaults to Indian English with Hindi/Marathi fallback.',
    system_prompt: prompt,
    max_call_minutes: 6,
    tools: [{
      name: 'escalate_existing_client',
      description: 'Call when an EXISTING client reports a complaint or urgent problem. Triggers an immediate senior alert.',
      method: 'POST', url: `${appBase()}/api/voice/tools/escalate`,
      headers: { 'x-webhook-secret': '<VAANI_WEBHOOK_SECRET>' },
      parameters: { name: 'string', project: 'string', designer_name: 'string', issue: 'string', caller_number: 'string' },
    }],
    post_call_webhook: { url: `${appBase()}/api/voice/webhook`, events: ['call_postprocessing'], signing: 'Vaani documents no signature, so the shared secret travels in the URL: add ?secret=<VAANI_WEBHOOK_SECRET> to the webhook URL' },
    routing: {
      weekdays_10_to_19: 'Front-desk phone rings first; after ~20 seconds (about 3 rings) it rolls over to this agent.',
      after_hours_and_sundays: 'Straight to this agent.',
    },
    never_say: rules.never_say,
    // Vaani fills in any {name} it finds in a prompt, so a stray brace would be read out loud to callers.
    warnings: /[{}]/.test(prompt) ? ['The prompt contains { or }: Vaani would treat them as variables. Remove them before pasting.'] : [] as string[],
  };
  const md = `# Aangan Studio phone assistant: agent configuration

**House Rules version ${rules.version}** · ${rules.approved_at ? `approved by ${rules.approved_by} on ${rules.approved_at}` : '**DRAFT: not approved by Nikhil yet. Do not put this agent live.**'}

Generated by \`npm run agent-config\` (or the House Rules screen). Paste the system prompt below into the Vaani agent's prompt / instructions field.

## Greeting (first message)
${OPENING_LINE}

## Languages
English, Hindi, Marathi, Hinglish: the agent mirrors the caller.

## Call routing for the studio line
- 10am–7pm, Monday–Saturday: the front-desk phone rings first; if nobody answers in ~20 seconds (about 3 rings) the call rolls over to the agent.
- After hours and Sundays: straight to the agent.

## Mid-call tool (optional, if your Vaani plan supports tools / custom actions)
- \`escalate_existing_client\` → POST ${appBase()}/api/voice/tools/escalate (header \`x-webhook-secret\`)
- If tools are not available, skip it: the pipeline escalates existing-client calls right after the call ends.

## Post-call webhook
POST ${appBase()}/api/voice/webhook · events \`call.completed\`, \`call.failed\` · HMAC-SHA256 signature of the raw body.

## Never say
${rules.never_say.map((x) => `- ${x}`).join('\n')}

## System prompt
\`\`\`
${prompt}
\`\`\`
`;
  return { json, md, prompt };
}
